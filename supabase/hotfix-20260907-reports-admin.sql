create or replace function public.submit_listing_report(
  p_listing_id uuid,
  p_reason public.listing_report_reason,
  p_details text default null
)
returns uuid
language plpgsql
security definer
set search_path = public
as $$
declare
  v_user_id uuid := (select auth.uid());
  v_report_id uuid;
  v_details text := nullif(trim(coalesce(p_details, '')), '');
begin
  if v_user_id is null then
    raise exception 'authentication_required' using errcode = '42501';
  end if;

  if not exists (
    select 1
    from public.listings listing
    where listing.id = p_listing_id
      and listing.status = 'active'
      and listing.deleted_at is null
      and listing.owner_id <> v_user_id
  ) then
    raise exception 'listing_not_reportable' using errcode = '22023';
  end if;

  if p_reason = 'other' and (v_details is null or length(v_details) < 10) then
    raise exception 'report_details_required' using errcode = '22023';
  end if;

  if v_details is not null and length(v_details) > 1000 then
    raise exception 'report_details_too_long' using errcode = '22023';
  end if;
  if v_details is not null and length(v_details) < 3 then
    raise exception 'report_details_too_short' using errcode = '22023';
  end if;

  if (
    select count(*)
    from public.listing_reports recent
    where recent.reporter_id = v_user_id
      and recent.created_at >= now() - interval '24 hours'
  ) >= 20 then
    raise exception 'report_rate_limit' using errcode = 'P0001';
  end if;

  insert into public.listing_reports (listing_id, reporter_id, reason, details)
  values (p_listing_id, v_user_id, p_reason, v_details)
  on conflict (listing_id, reporter_id) do nothing
  returning id into v_report_id;

  if v_report_id is null then
    select report.id into v_report_id
    from public.listing_reports report
    where report.listing_id = p_listing_id
      and report.reporter_id = v_user_id;
  end if;

  return v_report_id;
end;
$$;

create or replace function public.get_admin_dashboard_stats()
returns jsonb
language plpgsql
stable
security definer
set search_path = public
as $$
begin
  if not public.is_admin() then
    raise exception 'admin_required' using errcode = '42501';
  end if;

  return jsonb_build_object(
    'registered_users', (select count(*) from public.profiles where deleted_at is null),
    'new_users_24h', (select count(*) from public.profiles where created_at >= now() - interval '24 hours' and deleted_at is null),
    'total_listings', (select count(*) from public.listings where deleted_at is null),
    'active_listings', (select count(*) from public.listings where status = 'active' and deleted_at is null),
    'draft_listings', (select count(*) from public.listings where status in ('draft', 'media_processing', 'pending_moderation') and deleted_at is null),
    'admin_hidden_listings', (select count(*) from public.listings where admin_hidden and deleted_at is null),
    'open_reports', (select count(*) from public.listing_reports where status = 'open'),
    'reports_24h', (select count(*) from public.listing_reports where created_at >= now() - interval '24 hours'),
    'events_24h', (select count(*) from public.behavior_events where occurred_at >= now() - interval '24 hours'),
    'active_visitors_24h', (
      select count(distinct coalesce(user_id::text, anonymous_id::text))
      from public.behavior_events
      where occurred_at >= now() - interval '24 hours'
    ),
    'messages_total', (select count(*) from public.messages where deleted_at is null),
    'favorites_total', (select count(*) from public.favorites)
  );
end;
$$;

create or replace function public.get_admin_activity(p_days integer default 14)
returns table (
  activity_date date,
  registrations bigint,
  listings_created bigint,
  reports_created bigint,
  behavior_events bigint,
  messages_sent bigint,
  favorites_added bigint
)
language plpgsql
stable
security definer
set search_path = public
as $$
declare
  v_days integer := greatest(1, least(coalesce(p_days, 14), 90));
begin
  if not public.is_admin() then
    raise exception 'admin_required' using errcode = '42501';
  end if;

  return query
  select
    day_value::date,
    (select count(*) from public.profiles p where p.created_at >= day_value and p.created_at < day_value + interval '1 day'),
    (select count(*) from public.listings l where l.created_at >= day_value and l.created_at < day_value + interval '1 day'),
    (select count(*) from public.listing_reports r where r.created_at >= day_value and r.created_at < day_value + interval '1 day'),
    (select count(*) from public.behavior_events e where e.occurred_at >= day_value and e.occurred_at < day_value + interval '1 day'),
    (select count(*) from public.messages m where m.created_at >= day_value and m.created_at < day_value + interval '1 day' and m.deleted_at is null),
    (select count(*) from public.favorites f where f.created_at >= day_value and f.created_at < day_value + interval '1 day')
  from generate_series(
    current_date - (v_days - 1),
    current_date,
    interval '1 day'
  ) day_value
  order by day_value;
end;
$$;

create or replace function public.get_admin_reports(
  p_status text default 'open',
  p_limit integer default 50,
  p_offset integer default 0
)
returns table (
  id uuid,
  listing_id uuid,
  listing_title text,
  listing_status public.listing_status,
  listing_admin_hidden boolean,
  listing_cover_object_key text,
  reporter_id uuid,
  reporter_name text,
  reporter_phone text,
  reason public.listing_report_reason,
  details text,
  status public.listing_report_status,
  admin_note text,
  created_at timestamptz,
  handled_at timestamptz
)
language plpgsql
stable
security definer
set search_path = public
as $$
begin
  if not public.is_admin() then
    raise exception 'admin_required' using errcode = '42501';
  end if;

  return query
  select
    report.id,
    report.listing_id,
    listing.title,
    listing.status,
    listing.admin_hidden,
    (
      select media.object_key
      from public.listing_media media
      where media.listing_id = listing.id
        and media.kind = 'photo'
        and media.status = 'ready'
        and media.deleted_at is null
      order by media.sort_order, media.created_at
      limit 1
    ),
    report.reporter_id,
    coalesce(nullif(trim(profile.display_name), ''), 'Пользователь QazAuto'),
    profile.phone_e164,
    report.reason,
    report.details,
    report.status,
    report.admin_note,
    report.created_at,
    report.handled_at
  from public.listing_reports report
  join public.listings listing on listing.id = report.listing_id
  join public.profiles profile on profile.id = report.reporter_id
  where coalesce(p_status, 'all') = 'all'
     or report.status::text = p_status
  order by
    case when report.status = 'open' then 0 else 1 end,
    report.created_at desc
  limit greatest(1, least(coalesce(p_limit, 50), 100))
  offset greatest(coalesce(p_offset, 0), 0);
end;
$$;

create or replace function public.admin_review_listing_report(
  p_report_id uuid,
  p_status public.listing_report_status,
  p_admin_note text default null
)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  v_admin_id uuid := (select auth.uid());
  v_note text := nullif(trim(coalesce(p_admin_note, '')), '');
begin
  if not public.is_admin() then
    raise exception 'admin_required' using errcode = '42501';
  end if;
  if p_status not in ('reviewed', 'dismissed', 'actioned') then
    raise exception 'invalid_report_status' using errcode = '22023';
  end if;
  if v_note is not null and length(v_note) > 2000 then
    raise exception 'admin_note_too_long' using errcode = '22023';
  end if;
  update public.listing_reports
  set status = p_status,
      handled_by = v_admin_id,
      handled_at = now(),
      admin_note = v_note,
      updated_at = now()
  where id = p_report_id;

  if not found then
    raise exception 'report_not_found' using errcode = 'P0002';
  end if;

  insert into public.admin_audit_log (actor_id, action, target_type, target_id, details)
  values (
    v_admin_id,
    case when p_status = 'dismissed' then 'report_dismissed' else 'report_reviewed' end,
    'report',
    p_report_id,
    jsonb_build_object('status', p_status, 'note', v_note)
  );
end;
$$;

create or replace function public.admin_set_listing_visibility(
  p_listing_id uuid,
  p_visible boolean,
  p_reason text default null,
  p_report_id uuid default null
)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  v_admin_id uuid := (select auth.uid());
  v_reason text := nullif(trim(coalesce(p_reason, '')), '');
  v_is_hidden boolean;
begin
  if not public.is_admin() then
    raise exception 'admin_required' using errcode = '42501';
  end if;

  select listing.admin_hidden into v_is_hidden
  from public.listings listing
  where listing.id = p_listing_id
    and listing.deleted_at is null;

  if not found then
    raise exception 'listing_not_found' using errcode = 'P0002';
  end if;

  if p_visible then
    if not v_is_hidden then
      raise exception 'listing_not_hidden_by_admin' using errcode = '22023';
    end if;

    update public.listings
    set status = 'active',
        admin_hidden = false,
        admin_hidden_at = null,
        admin_hidden_by = null,
        admin_hidden_reason = null,
        archived_at = null,
        rejection_reason = null,
        expires_at = now() + interval '30 days',
        version = version + 1,
        updated_at = now()
    where id = p_listing_id;
  else
    if v_reason is null or length(v_reason) < 3 then
      raise exception 'hide_reason_required' using errcode = '22023';
    end if;

    update public.listings
    set status = 'archived',
        admin_hidden = true,
        admin_hidden_at = now(),
        admin_hidden_by = v_admin_id,
        admin_hidden_reason = v_reason,
        archived_at = now(),
        rejection_reason = 'Скрыто администратором: ' || v_reason,
        version = version + 1,
        updated_at = now()
    where id = p_listing_id;

    if p_report_id is not null then
      update public.listing_reports
      set status = 'actioned',
          handled_by = v_admin_id,
          handled_at = now(),
          admin_note = v_reason,
          updated_at = now()
      where id = p_report_id
        and listing_id = p_listing_id;
    end if;
  end if;

  insert into public.admin_audit_log (actor_id, action, target_type, target_id, details)
  values (
    v_admin_id,
    case when p_visible then 'listing_restored' else 'listing_hidden' end,
    'listing',
    p_listing_id,
    jsonb_build_object('reason', v_reason, 'report_id', p_report_id)
  );
end;
$$;

create or replace function public.promote_admin_by_phone(p_phone_e164 text)
returns uuid
language plpgsql
security definer
set search_path = public
as $$
declare
  v_user_id uuid;
begin
  select profile.id into v_user_id
  from public.profiles profile
  where profile.phone_e164 = p_phone_e164
    and profile.phone_verified_at is not null
    and profile.deleted_at is null;

  if v_user_id is null then
    raise exception 'verified_profile_not_found' using errcode = 'P0002';
  end if;

  insert into public.account_roles (user_id, role)
  values (v_user_id, 'admin')
  on conflict do nothing;

  insert into public.admin_audit_log (actor_id, action, target_type, target_id, details)
  values (v_user_id, 'admin_granted', 'profile', v_user_id, jsonb_build_object('phone', p_phone_e164));

  return v_user_id;
end;
$$;

