do $$
begin
  create type public.listing_report_reason as enum (
    'not_vehicle',
    'fraud',
    'wrong_information',
    'duplicate',
    'other'
  );
exception when duplicate_object then null;
end $$;

do $$
begin
  create type public.listing_report_status as enum (
    'open',
    'reviewed',
    'dismissed',
    'actioned'
  );
exception when duplicate_object then null;
end $$;

alter table public.listings
  add column if not exists admin_hidden boolean not null default false,
  add column if not exists admin_hidden_at timestamptz,
  add column if not exists admin_hidden_by uuid references public.profiles(id) on delete set null,
  add column if not exists admin_hidden_reason text;

create table if not exists public.listing_reports (
  id uuid primary key default gen_random_uuid(),
  listing_id uuid not null references public.listings(id) on delete cascade,
  reporter_id uuid not null references public.profiles(id) on delete cascade,
  reason public.listing_report_reason not null,
  details text,
  status public.listing_report_status not null default 'open',
  handled_by uuid references public.profiles(id) on delete set null,
  handled_at timestamptz,
  admin_note text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (listing_id, reporter_id),
  check (details is null or length(trim(details)) between 3 and 1000),
  check (admin_note is null or length(trim(admin_note)) between 1 and 2000)
);

create table if not exists public.admin_audit_log (
  id bigint generated by default as identity primary key,
  actor_id uuid not null references public.profiles(id) on delete restrict,
  action text not null,
  target_type text not null,
  target_id uuid,
  details jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  check (action in ('report_reviewed', 'report_dismissed', 'listing_hidden', 'listing_restored', 'admin_granted')),
  check (target_type in ('report', 'listing', 'profile'))
);

create index if not exists listing_reports_status_recent_idx
  on public.listing_reports (status, created_at desc);
create index if not exists listing_reports_listing_idx
  on public.listing_reports (listing_id, created_at desc);
create index if not exists profiles_created_at_idx
  on public.profiles (created_at desc);
create index if not exists listings_created_at_idx
  on public.listings (created_at desc);
create index if not exists messages_created_at_idx
  on public.messages (created_at desc);
create index if not exists favorites_created_at_idx
  on public.favorites (created_at desc);
create index if not exists admin_audit_recent_idx
  on public.admin_audit_log (created_at desc);

alter table public.listing_reports enable row level security;
alter table public.admin_audit_log enable row level security;

create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1
    from public.account_roles roles
    where roles.user_id = (select auth.uid())
      and roles.role = 'admin'
  );
$$;

