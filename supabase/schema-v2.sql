create or replace function public.validate_listing_relationships()
returns trigger
language plpgsql
as $$
begin
  if new.dealer_id is not null and not exists (
    select 1
    from public.dealers
    where dealers.id = new.dealer_id
      and dealers.owner_id = new.owner_id
      and dealers.verification_status = 'verified'
  ) then
    raise exception 'Dealer does not belong to the listing owner or is not verified';
  end if;

  if new.model_id is not null and not exists (
    select 1
    from public.vehicle_models
    where vehicle_models.id = new.model_id
      and (new.brand_id is null or vehicle_models.brand_id = new.brand_id)
  ) then
    raise exception 'Vehicle model does not belong to the selected brand';
  end if;

  return new;
end;
$$;

create or replace function public.log_listing_status_change()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if tg_op = 'INSERT' or new.status is distinct from old.status then
    insert into public.listing_status_history (
      listing_id,
      old_status,
      new_status,
      changed_by
    )
    values (
      new.id,
      case when tg_op = 'INSERT' then null else old.status end,
      new.status,
      (select auth.uid())
    );
  end if;
  return new;
end;
$$;

create or replace function public.update_favorite_counter()
returns trigger
