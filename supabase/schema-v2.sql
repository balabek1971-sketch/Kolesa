      updated_at = now()
  where listing_id = old.listing_id;
  return old;
end;
$$;

create or replace function public.submit_listing_for_moderation(
  p_listing_id uuid,
  p_owner_id uuid
)
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  if not exists (
    select 1
    from public.profiles
    where id = p_owner_id
      and status = 'active'
      and phone_verified_at is not null
      and deleted_at is null
  ) then
    raise exception 'A verified phone number is required';
  end if;

  if not exists (
    select 1
    from public.listings
    where id = p_listing_id
      and owner_id = p_owner_id
      and status in ('draft', 'rejected')
      and deleted_at is null
  ) then
    raise exception 'Listing cannot be submitted';
  end if;

  if not exists (
    select 1
    from public.listing_media
    where listing_id = p_listing_id
      and kind = 'photo'
      and status = 'ready'
      and deleted_at is null
  ) then
    raise exception 'At least one ready photo is required';
  end if;

  update public.listings
  set status = 'pending_moderation',
      rejection_reason = null,
      version = version + 1,
      updated_at = now()
  where id = p_listing_id;
end;
$$;

create or replace function public.moderate_listing(
  p_listing_id uuid,
  p_moderator_id uuid,
  p_decision public.moderation_decision,
  p_reason text default null
)
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  if not exists (
    select 1
    from public.account_roles
    where user_id = p_moderator_id
      and role in ('moderator', 'admin')
  ) then
    raise exception 'Moderator role is required';
  end if;

  if not exists (
    select 1
    from public.listings
    where id = p_listing_id
      and status = 'pending_moderation'
      and deleted_at is null
  ) then
    raise exception 'Listing is not pending moderation';
  end if;

  insert into public.moderation_reviews (
    listing_id,
    moderator_id,
    decision,
    reason
  ) values (
    p_listing_id,
    p_moderator_id,
    p_decision,
    nullif(trim(p_reason), '')
  );

  if p_decision = 'approved' then
    update public.listings
    set status = 'active',
        rejection_reason = null,
        published_at = now(),
        expires_at = now() + interval '30 days',
        version = version + 1,
        updated_at = now()
    where id = p_listing_id;
  else
    update public.listings
    set status = 'rejected',
        rejection_reason = coalesce(nullif(trim(p_reason), ''), 'Changes required'),
        version = version + 1,
        updated_at = now()
    where id = p_listing_id;
  end if;
end;
$$;

create or replace function public.expire_listings()
returns integer
language plpgsql
security definer
set search_path = public
as $$
declare
  affected integer;
begin
  update public.listings
  set status = 'expired',
      updated_at = now()
  where status = 'active'
    and expires_at <= now();

  get diagnostics affected = row_count;
  return affected;
end;
$$;

